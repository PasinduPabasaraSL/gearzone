import { discountPercent } from '../utils/formatCurrency'
import { categoryBySlug } from './categories'
import { resolveImages } from './media'

/**
 * Mock catalogue. Records are written in a compact authoring shape and
 * expanded by `defineProduct` into the full shape the UI consumes, so derived
 * fields (discount, images, stock badge) can never drift out of sync.
 *
 * Brands are sample data only; see brands.js.
 */

const LOW_STOCK_THRESHOLD = 5

function defineProduct(record) {
  const images = resolveImages(record.images)
  const discount = discountPercent(record.price, record.compareAtPrice)
  const category = categoryBySlug.get(record.category)
  if (!category) throw new Error(`Unknown category "${record.category}" on ${record.id}`)

  return {
    compareAtPrice: null,
    featured: false,
    trending: false,
    tags: [],
    highlights: [],
    ...record,
    categoryName: category.name,
    discount,
    images,
    thumbnail: images[0].src,
    badge: record.stock === 0 ? 'OUT OF STOCK' : (record.badge ?? (discount >= 15 ? 'SALE' : null)),
    lowStock: record.stock > 0 && record.stock <= LOW_STOCK_THRESHOLD,
  }
}

